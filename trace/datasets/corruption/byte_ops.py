def noise_overwrite(
    data: bytes,
    offset_start: int,
    length: int,
    rng: random.Random,
) -> Tuple[bytes, CorruptionOperation]:
    """Overwrite a byte range with pseudorandom noise generated by rng."""
    if not data:
        return data, CorruptionOperation(
            operation_id=str(uuid.uuid4())[:8],
            type=CorruptionType.NOISE_OVERWRITE,
            offset_start=0,
            offset_end=0,
            original_length=0,
            corrupted_length=0,
            severity=0.0,
            recoverability=Recoverability.FULL,
            reversible=False,
        )

    start = max(0, min(offset_start, len(data) - 1))
    end = max(start, min(start + length, len(data)))
    actual_len = end - start

    noise = bytes(rng.getrandbits(8) for _ in range(actual_len))
    corrupted = data[:start] + noise + data[end:]
    severity = actual_len / max(1, len(data))

    op = CorruptionOperation(
        operation_id=str(uuid.uuid4())[:8],
        type=CorruptionType.NOISE_OVERWRITE,
        offset_start=start,
        offset_end=end,
        original_length=actual_len,
        corrupted_length=actual_len,
        severity=round(severity, 3),
        recoverability=Recoverability.UNRECOVERABLE_WITHOUT_EXTERNAL_REDUNDANCY,
        reversible=False,
        details={"noise_bytes_count": actual_len},
    )
    return corrupted, op


def duplicate_bytes(
    data: bytes,
    offset_start: int,
    length: int,
    insert_pos: int,
) -> Tuple[bytes, CorruptionOperation]:
    """Duplicate a slice of bytes and insert it at insert_pos."""
    start = max(0, min(offset_start, len(data) - 1))
    end = max(start, min(start + length, len(data)))
    actual_len = end - start
    chunk = data[start:end]

    pos = max(0, min(insert_pos, len(data)))
    corrupted = data[:pos] + chunk + data[pos:]

    op = CorruptionOperation(
        operation_id=str(uuid.uuid4())[:8],
        type=CorruptionType.DUPLICATE_BYTES,
        offset_start=pos,
        offset_end=pos + actual_len,
        original_length=0,
        corrupted_length=actual_len,
        severity=round(actual_len / max(1, len(data)), 3),
        recoverability=Recoverability.RECOVERABLE_FROM_SURVIVING_EVIDENCE,
        reversible=True,
        details={"duplicated_from": [start, end], "length": actual_len},
    )
    return corrupted, op


def insert_garbage(
    data: bytes,
    insert_pos: int,
    garbage: bytes,
) -> Tuple[bytes, CorruptionOperation]:
    """Insert garbage bytes at insert_pos."""
    pos = max(0, min(insert_pos, len(data)))
    corrupted = data[:pos] + garbage + data[pos:]

    op = CorruptionOperation(
        operation_id=str(uuid.uuid4())[:8],
        type=CorruptionType.INSERT_GARBAGE,
        offset_start=pos,
        offset_end=pos + len(garbage),
        original_length=0,
        corrupted_length=len(garbage),
        severity=round(len(garbage) / max(1, len(data)), 3),
        recoverability=Recoverability.RECOVERABLE_FROM_SURVIVING_EVIDENCE,
        reversible=True,
        details={"garbage_length": len(garbage)},
    )
    return corrupted, op
