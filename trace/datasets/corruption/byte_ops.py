"""Byte-level corruption operators."""

from __future__ import annotations

import random
import uuid
from typing import Tuple

from trace.datasets.schemas.corruption import (
    CorruptionOperation,
    CorruptionType,
    Recoverability,
)


def delete_bytes(
    data: bytes,
    offset_start: int,
    length: int,
) -> Tuple[bytes, CorruptionOperation]:
    """Delete a contiguous byte range from data."""
    if not data:
        return data, CorruptionOperation(
            operation_id=str(uuid.uuid4())[:8],
            type=CorruptionType.DELETE_BYTES,
            offset_start=0,
            offset_end=0,
            original_length=0,
            corrupted_length=0,
            severity=0.0,
            recoverability=Recoverability.FULL,
            reversible=False,
        )

    start = max(0, min(offset_start, len(data) - 1))
    end = max(start, min(start + length, len(data)))
    actual_len = end - start

    corrupted = data[:start] + data[end:]
    severity = min(1.0, actual_len / max(1, len(data)))

    op = CorruptionOperation(
        operation_id=str(uuid.uuid4())[:8],
        type=CorruptionType.DELETE_BYTES,
        offset_start=start,
        offset_end=end,
        original_length=actual_len,
        corrupted_length=0,
        severity=round(severity, 3),
        recoverability=Recoverability.UNRECOVERABLE_WITHOUT_EXTERNAL_REDUNDANCY,
        reversible=False,
        details={"deleted_bytes_count": actual_len},
    )
    return corrupted, op


def truncate_bytes(
    data: bytes,
    target_length: int,
) -> Tuple[bytes, CorruptionOperation]:
    """Truncate file at target_length."""
    if target_length >= len(data):
        return data, CorruptionOperation(
            operation_id=str(uuid.uuid4())[:8],
            type=CorruptionType.TRUNCATE,
            offset_start=len(data),
            offset_end=len(data),
            original_length=0,
            corrupted_length=0,
            severity=0.0,
            recoverability=Recoverability.FULL,
            reversible=False,
        )

    target = max(0, target_length)
    corrupted = data[:target]
    lost = len(data) - target
    severity = lost / max(1, len(data))

    op = CorruptionOperation(
        operation_id=str(uuid.uuid4())[:8],
        type=CorruptionType.TRUNCATE,
        offset_start=target,
        offset_end=len(data),
        original_length=lost,
        corrupted_length=0,
        severity=round(severity, 3),
        recoverability=Recoverability.UNRECOVERABLE_WITHOUT_EXTERNAL_REDUNDANCY,
        reversible=False,
        details={"lost_bytes_count": lost},
    )
    return corrupted, op


